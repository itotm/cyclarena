#!/usr/bin/env bun
// Builds the distributable versions of paintarena with Bun:
//   - a single executable (bun build --compile) with the site embedded,
//     which with no arguments opens the game in the browser and with a
//     command acts as the command line;
//   - for Windows: portable folder, zip and installer (NSIS, if available).
//
// Usage: bun scripts/dist.ts [windows|linux|macos|all]   (default: windows)
// Installer: needs makensis in the PATH (Debian: apt install nsis) or the
// MAKENSIS variable set to the program's path.

import { $ } from "bun";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const SITE = join(ROOT, "apps/web/dist");
const BUILD = join(ROOT, "packages/cli/build");
const OUT = join(ROOT, "dist");
const VERSION: string = JSON.parse(readFileSync(join(ROOT, "packages/cli/package.json"), "utf8")).version;

const TARGETS = {
  windows: { bun: "bun-windows-x64-baseline", exe: "paintarena.exe", dir: `paintarena-${VERSION}-windows-x64` },
  linux: { bun: "bun-linux-x64", exe: "paintarena", dir: `paintarena-${VERSION}-linux-x64` },
  macos: { bun: "bun-darwin-arm64", exe: "paintarena", dir: `paintarena-${VERSION}-macos-arm64` },
} as const;
type Target = keyof typeof TARGETS;

const MIME: Record<string, string> = {
  html: "text/html; charset=utf-8", js: "text/javascript; charset=utf-8", css: "text/css; charset=utf-8",
  svg: "image/svg+xml", png: "image/png", ico: "image/x-icon", json: "application/json", txt: "text/plain; charset=utf-8",
  woff2: "font/woff2",
};

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const step = (msg: string) => console.log(`\n▸ ${msg}`);

// 1. static site
step("Site (vite build)");
await $`pnpm --filter @paintarena/web build`.cwd(ROOT).quiet();

// 2. entry point with the list of site files to embed
step("Embedding the site in the executable");
mkdirSync(BUILD, { recursive: true });
const files = walk(SITE);
const lines = [
  "// Generated by scripts/dist.ts: do not edit.",
  'import { runApp } from "../src/app.ts";',
];
const entries: string[] = [];
files.forEach((f, i) => {
  const url = "/" + relative(SITE, f).replaceAll("\\", "/");
  const ext = f.split(".").pop() ?? "";
  lines.push(`import f${i} from ${JSON.stringify(relative(BUILD, f).replaceAll("\\", "/"))} with { type: "file" };`);
  entries.push(`  ${JSON.stringify(url)}: { path: f${i}, type: ${JSON.stringify(MIME[ext] ?? "application/octet-stream")} },`);
});
lines.push("await runApp({", ...entries, "});", "");
writeFileSync(join(BUILD, "entry.ts"), lines.join("\n"));
console.log(`  ${files.length} files`);

// 3. Windows icon
function makeIcon(): string | null {
  const ico = join(BUILD, "paintarena.ico");
  const svg = join(ROOT, "apps/web/public/favicon.svg");
  const r = Bun.spawnSync(["magick", "-background", "none", "-density", "384", svg, "-define", "icon:auto-resize=256,64,48,32,16", ico]);
  return r.exitCode === 0 && existsSync(ico) ? ico : null;
}

const README = `paintarena ${VERSION}
================

[IT] Per giocare apri paintarena (doppio clic): il gioco si apre nel browser.
     Per chiudere paintarena chiudi la finestra nera che compare.
     Riga di comando: paintarena help
     Robot di esempio nella cartella "robots/it".
     Robot e progressi restano sul tuo computer, nel browser: niente va in rete.

     paintarena è un omaggio a CROBOTS di Tom Poindexter (1985).
     Software libero: GNU GPL versione 3 o successive (LICENSE.txt).

[EN] To play open paintarena (double click): the game opens in your browser.
     To quit paintarena close the black window that appears.
     Command line: paintarena help
     Example robots in the "robots/en" folder.
     Robots and progress stay on your computer, in the browser: nothing goes online.
     paintarena is a tribute to Tom Poindexter's CROBOTS (1985).
     Free software: GNU GPL version 3 or later (LICENSE.txt).

Source code: https://github.com/itotm/paintarena
`;

async function buildTarget(name: Target) {
  const t = TARGETS[name];
  const dir = join(OUT, t.dir);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(join(dir, "robots"), { recursive: true });

  step(`Executable ${name} (${t.bun})`);
  const icon = name === "windows" ? makeIcon() : null;
  const base = [process.execPath, "build", "--compile", "--minify", `--target=${t.bun}`,
    join(BUILD, "entry.ts"), join(ROOT, "packages/cli/src/worker.ts"), "--outfile", join(dir, t.exe)];
  let r = Bun.spawnSync(icon ? [...base, `--windows-icon=${icon}`, "--windows-title=paintarena", `--windows-version=${VERSION}.0`] : base,
    { stdout: "inherit", stderr: "pipe" });
  if (r.exitCode !== 0 && icon) {
    // the --windows-* options are not available when building from Linux: no icon is fine too
    console.log("  (the executable icon cannot be applied from this system: the shortcuts use it)");
    r = Bun.spawnSync(base, { stdout: "inherit", stderr: "inherit" });
  }
  if (r.exitCode !== 0) { console.error(r.stderr?.toString()); process.exit(1); }

  // accompanying files
  const crlf = (s: string) => (name === "windows" ? s.replace(/\r?\n/g, "\r\n") : s);
  writeFileSync(join(dir, "LICENSE.txt"), crlf(readFileSync(join(ROOT, "LICENSE"), "utf8")));
  writeFileSync(join(dir, name === "windows" ? "README.txt" : "README"), crlf(README));
  for (const f of readdirSync(join(ROOT, "robots"))) cpSync(join(ROOT, "robots", f), join(dir, "robots", f), { recursive: true });
  if (icon) cpSync(icon, join(dir, "paintarena.ico"));

  if (name !== "windows") {
    await $`tar -czf ${t.dir}.tar.gz ${t.dir}`.cwd(OUT).quiet();
    console.log(`  → dist/${t.dir}.tar.gz`);
    return;
  }

  step("Portable zip");
  rmSync(join(OUT, `${t.dir}.zip`), { force: true });
  await $`zip -qr ${t.dir}.zip ${t.dir}`.cwd(OUT);
  console.log(`  → dist/${t.dir}.zip`);

  step("Installer (NSIS)");
  const makensis = process.env.MAKENSIS ?? Bun.which("makensis");
  if (!makensis) {
    console.log("  makensis not found: install NSIS (Debian: sudo apt install nsis) to build the installer.");
    return;
  }
  if (!icon) { console.log("  ImageMagick (magick) is needed for the installer icon."); return; }
  // list of installed files, so uninstalling touches nothing else
  const installed = walk(dir).map((f) => relative(dir, f).replaceAll("/", "\\"));
  const dirs = [...new Set(installed.filter((f) => f.includes("\\")).map((f) => f.slice(0, f.lastIndexOf("\\"))))];
  const fileList = join(BUILD, "uninstall-files.nsh");
  writeFileSync(fileList, [
    ...installed.map((f) => `  Delete "$INSTDIR\\${f}"`),
    ...dirs.sort((a, b) => b.length - a.length).map((d) => `  RMDir "$INSTDIR\\${d}"`),
    "",
  ].join("\r\n"));
  const setup = join(OUT, `paintarena-${VERSION}-setup.exe`);
  const n = Bun.spawnSync([makensis, "-V2", `-DVERSION=${VERSION}`, `-DSRCDIR=${dir}`, `-DOUTFILE=${setup}`,
    `-DICON=${icon}`, `-DFILELIST=${fileList}`, join(ROOT, "scripts/windows/installer.nsi")], { stdout: "inherit", stderr: "inherit" });
  if (n.exitCode !== 0) process.exit(1);
  console.log(`  → dist/paintarena-${VERSION}-setup.exe`);
}

const arg = (process.argv[2] ?? "windows") as Target | "all";
const list: Target[] = arg === "all" ? ["windows", "linux", "macos"] : [arg];
if (!list.every((t) => t in TARGETS)) {
  console.error("Usage: bun scripts/dist.ts [windows|linux|macos|all]");
  process.exit(2);
}
mkdirSync(OUT, { recursive: true });
for (const t of list) await buildTarget(t);
console.log("\nDone.");
